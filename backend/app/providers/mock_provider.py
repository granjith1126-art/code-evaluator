from typing import Dict, Any, List
from app.providers.base import BaseAIProvider

class MockAIProvider(BaseAIProvider):
    """
    Deterministic offline mock provider.
    Provides realistic, reproducible evaluation and comparison reports.
    """

    def is_configured(self) -> bool:
        return True

    def evaluate_code(
        self,
        problem_title: str,
        problem_description: str,
        code: str,
        test_summary: Dict[str, Any]
    ) -> Dict[str, Any]:
        pass_rate = test_summary.get("pass_rate", 100.0)
        status = test_summary.get("status", "Accepted")
        is_clean = (status == "Accepted")

        correctness = min(100.0, max(20.0, pass_rate))
        efficiency = 88.0 if is_clean else 40.0
        readability = 85.0 if len(code.splitlines()) < 40 else 70.0
        maintainability = 82.0
        security = 95.0
        robustness = 80.0 if is_clean else 45.0
        edge_cases = 85.0 if is_clean else 35.0
        instruction_following = 90.0

        bugs = []
        if not is_clean:
            bugs.append({
                "title": f"Failed Execution: {status}",
                "line_number": 1,
                "severity": "high",
                "description": f"The code resulted in {status}. Error category: {test_summary.get('error_category', 'Unknown')}",
                "suggestion": "Review boundary conditions and verify function return types against expected test specifications."
            })

        optimizations = [
            {
                "category": "time_complexity",
                "current_state": "Linear or quadratic pass over input data",
                "improved_state": "Optimal algorithm using hash maps or two pointers where applicable",
                "rationale": "Reduces auxiliary runtime overhead on large problem constraints."
            },
            {
                "category": "readability",
                "current_state": "Direct imperative loops",
                "improved_state": "Add type annotations and concise docstrings",
                "rationale": "Improves long-term maintainability and readability for peer review."
            }
        ]

        assessment = (
            f"The solution for '{problem_title}' achieved a pass rate of {pass_rate}%. "
            f"Overall code structure is {'clean and modular' if is_clean else 'requires attention on edge cases and failure handling'}. "
            "Algorithmic complexity appears appropriate for standard constraints."
        )

        return {
            "provider": "mock",
            "model": "mock-evaluator-v1",
            "overall_assessment": assessment,
            "correctness_score": correctness,
            "efficiency_score": efficiency,
            "readability_score": readability,
            "maintainability_score": maintainability,
            "security_score": security,
            "robustness_score": robustness,
            "edge_cases_score": edge_cases,
            "instruction_following_score": instruction_following,
            "bugs_identified": bugs,
            "optimization_suggestions": optimizations,
            "confidence": 0.95,
            "raw_response": "Generated by deterministic mock provider."
        }

    def compare_solutions(
        self,
        problem_title: str,
        problem_description: str,
        solution_a: str,
        solution_b: str,
        metrics_a: Dict[str, Any],
        metrics_b: Dict[str, Any]
    ) -> Dict[str, Any]:
        score_a = metrics_a.get("total_score", 0.0)
        score_b = metrics_b.get("total_score", 0.0)

        if score_a > score_b:
            preferred = "A"
            justification = f"Solution A is preferred due to higher overall score ({score_a} vs {score_b}) and superior test pass performance."
        elif score_b > score_a:
            preferred = "B"
            justification = f"Solution B is preferred due to higher overall score ({score_b} vs {score_a}) and superior test pass performance."
        else:
            time_a = metrics_a.get("execution_time_ms", 0.0)
            time_b = metrics_b.get("execution_time_ms", 0.0)
            if time_a < time_b:
                preferred = "A"
                justification = f"Both solutions achieved identical scores ({score_a}), but Solution A executed faster ({time_a}ms vs {time_b}ms)."
            elif time_b < time_a:
                preferred = "B"
                justification = f"Both solutions achieved identical scores ({score_b}), but Solution B executed faster ({time_b}ms vs {time_a}ms)."
            else:
                preferred = "tie"
                justification = "Both solutions demonstrated equivalent functional correctness and runtime characteristics."

        return {
            "provider": "mock",
            "model": "mock-evaluator-v1",
            "preferred_solution": preferred,
            "functional_comparison": f"Solution A pass rate: {metrics_a.get('pass_rate', 0)}%, Solution B pass rate: {metrics_b.get('pass_rate', 0)}%.",
            "efficiency_comparison": f"Solution A runtime: {metrics_a.get('execution_time_ms', 0)}ms, Solution B runtime: {metrics_b.get('execution_time_ms', 0)}ms.",
            "readability_comparison": "Both solutions follow conventional Python syntax with clear variable naming.",
            "edge_case_comparison": "Handling of boundary conditions is consistent with the deterministic test outcomes.",
            "written_justification": justification,
            "confidence": 0.92
        }
